-- interestsect: Basiseinträge Nähen/Häkeln + Klammer-Sweep
--
-- Anlass: "Nähen" und "Häkeln" fehlten als einfache Basiseinträge;
-- einengende Klammer-Zusätze werden entfernt. Klärende Klammern zur
-- Disambiguierung bleiben (Go Brettspiel vs. Programmiersprache,
-- Kongo Republik vs. DR, Swift/Kotlin/Julia/C/R als Sprachen).
--
-- Idempotent: Inserts ON CONFLICT DO NOTHING, Updates mit Bedingung.


insert into public.interests (category_id, slug, name_de, keywords)
select c.id, v.slug, v.name_de, v.keywords
from (values
  ('handwerk-making','naehen','Nähen',array['stoff','maschine']),
  ('handwerk-making','haekeln','Häkeln',array['wolle','maschen'])
) as v(cat, slug, name_de, keywords)
join public.interest_categories c on c.slug = v.cat
on conflict (slug) do nothing;


